#!/usr/bin/env node
/*
 * Builds the site's icon sprite (audit D-08: pages carried 63-143 inline SVG
 * icons, duplicated again in the Next.js payload).
 *
 *   node scripts/build-icon-sprite.mjs        (also runs before `next build`)
 *
 * 1. Scans app/ for icons imported from app/Components/icons (or directly
 *    from react-icons/<pack>).
 * 2. Renders each icon once with react-icons and writes them as <symbol>s to
 *    public/icons.svg.
 * 3. Writes app/Components/icons.tsx: one tiny component per icon that renders
 *    <svg><use href="/icons.svg?v=<hash>#Name"/></svg>. Props work as they did
 *    with react-icons (className, style, aria-*).
 *
 * To use a new icon: import it from "../Components/icons" (relative path) like
 * any react-icons icon, then run this script (or `npm run build`).
 */
import { createHash } from "node:crypto";
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";

const ROOT = process.cwd();
const APP = join(ROOT, "app");
const OUT_SPRITE = join(ROOT, "public", "icons.svg");
const OUT_MODULE = join(APP, "Components", "icons.tsx");

/** react-icons pack for each export-name prefix used on the site. */
const PACKS = { Ri: "ri", Si: "si", Gr: "gr", Fa: "fa", Fi: "fi", Md: "md", Hi: "hi", Bs: "bs", Io: "io5", Lu: "lu", Tb: "tb" };

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (/\.(jsx?|tsx?)$/.test(name) && p !== OUT_MODULE) out.push(p);
  }
  return out;
}

const IMPORT = /import\s*\{([^}]*)\}\s*from\s*["']([^"']*(?:react-icons\/[a-z0-9]+|Components\/icons|\.\/icons))["']/g;
const names = new Set();
for (const file of walk(APP)) {
  const src = readFileSync(file, "utf8");
  for (const m of src.matchAll(IMPORT)) {
    for (const raw of m[1].split(",")) {
      const name = raw.trim().split(/\s+as\s+/)[0];
      if (name) names.add(name);
    }
  }
}

const sorted = [...names].sort();
const symbols = [];
for (const name of sorted) {
  const pack = PACKS[name.slice(0, 2)];
  if (!pack) throw new Error(`No react-icons pack known for ${name}`);
  const mod = await import(`react-icons/${pack}`);
  const Icon = mod[name];
  if (!Icon) throw new Error(`react-icons/${pack} has no export ${name}`);
  const svg = renderToStaticMarkup(createElement(Icon));
  const viewBox = /viewBox="([^"]+)"/.exec(svg)[1];
  const open = /^<svg([^>]*)>/.exec(svg)[1];
  // Keep presentation attributes that differ between packs (stroke icons).
  const keep = [...open.matchAll(/\s(fill|stroke|stroke-width|stroke-linecap|stroke-linejoin)="([^"]*)"/g)]
    .filter(([, k, v]) => !(k === "stroke-width" && v === "0") && !(k === "fill" && v === "currentColor") && !(k === "stroke" && v === "currentColor"))
    .map(([, k, v]) => ` ${k}="${v}"`)
    .join("");
  const inner = svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "");
  symbols.push(`<symbol id="${name}" viewBox="${viewBox}"${keep}>${inner}</symbol>`);
}

const sprite = `<svg xmlns="http://www.w3.org/2000/svg">${symbols.join("")}</svg>\n`;
const hash = createHash("sha1").update(sprite).digest("hex").slice(0, 10);
writeFileSync(OUT_SPRITE, sprite);

const moduleSrc = `// GENERATED by scripts/build-icon-sprite.mjs. Do not edit by hand.
// Each icon renders a <use> reference into /icons.svg (one cached file)
// instead of inlining its paths into every page's HTML and RSC payload.
import type { SVGProps } from "react";

const SPRITE = "/icons.svg?v=${hash}";

export type IconProps = SVGProps<SVGSVGElement> & { size?: string | number; title?: string };

function icon(id: string) {
  function SpriteIcon({ size = "1em", className, style, title, ...rest }: IconProps) {
    return (
      <svg
        width={size}
        height={size}
        fill="currentColor"
        stroke="currentColor"
        strokeWidth="0"
        className={className}
        style={style}
        aria-hidden={title ? undefined : true}
        focusable="false"
        {...rest}
      >
        {title && <title>{title}</title>}
        <use href={\`\${SPRITE}#\${id}\`} />
      </svg>
    );
  }
  SpriteIcon.displayName = id;
  return SpriteIcon;
}

${sorted.map((n) => `export const ${n} = icon("${n}");`).join("\n")}
`;
writeFileSync(OUT_MODULE, moduleSrc);

console.log(`icons: ${sorted.length} symbols, ${(sprite.length / 1024).toFixed(1)} KB -> ${relative(ROOT, OUT_SPRITE)} (v=${hash})`);
